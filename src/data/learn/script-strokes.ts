import type { Pt } from '@/lib/learn/strokes';

/**
 * Stroke paths written for this app for the Cyrillic capitals, the Arabic letters (isolated forms, dots after the body)
 * and Devanagari (headline last), in a 109×109 box like KanjiVG's. Each stroke is its centre line, in drawing order.
 */

/** Points along an ellipse from angle a0 to a1 (degrees; 0 = right, 90 = down, so increasing = clockwise on screen). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 12): Pt[] {
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    return [Math.round((cx + rx * Math.cos(a)) * 10) / 10, Math.round((cy + ry * Math.sin(a)) * 10) / 10] as Pt;
  });
}
/** A short tap-sized stroke for dots. */
const dot = (x: number, y: number): Pt[] => [
  [x, y],
  [x + 1.5, y + 1.5],
];

