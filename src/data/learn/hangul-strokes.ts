import type { Pt } from '@/lib/learn/strokes';

/** A circle drawn anticlockwise from the top, as Hangul ㅇ is written. */
function ring(cx: number, cy: number, r: number): Pt[] {
  return Array.from({ length: 17 }, (_, i) => {
    const a = -Math.PI / 2 - (i / 16) * Math.PI * 2;
    return [Math.round((cx + r * Math.cos(a)) * 10) / 10, Math.round((cy + r * Math.sin(a)) * 10) / 10] as Pt;
  });
}

