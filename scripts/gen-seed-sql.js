// Generates supabase/seed.sql from the book library in src/data/library so the app's offline data and the database stay in sync.
// Quotes, poems and facts are bundled with the app only.
const fs = require('fs');
const path = require('path');

const libraryDir = path.join(__dirname, '..', 'src', 'data', 'library');
const library = fs
  .readdirSync(libraryDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(fs.readFileSync(path.join(libraryDir, f), 'utf8')));

const topics = library.map((f) => f.topic);
const sources = library.flatMap((f) => f.books);
const ideas = library.flatMap((f) =>
  f.books.flatMap((book) =>
    book.ideas.map(([title, body, id], i) => ({ id: id ?? `${book.id}-${i + 1}`, topicId: f.topic.id, sourceId: book.id, title, body })),
  ),
);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = (items, cols) => items.map((item) => `  (${cols.map((c) => q(item[c])).join(', ')})`).join(',\n');

const sql = `-- Generated by scripts/gen-seed-sql.js. Edit src/data/library/*.json instead.
insert into topics (id, name, emoji, color) values
${rows(topics, ['id', 'name', 'emoji', 'color'])}
on conflict (id) do update set name = excluded.name, emoji = excluded.emoji, color = excluded.color;

insert into sources (id, title, author, kind) values
${rows(sources, ['id', 'title', 'author', 'kind'])}
on conflict (id) do update set title = excluded.title, author = excluded.author, kind = excluded.kind;

insert into ideas (id, topic_id, source_id, title, body) values
${rows(ideas, ['id', 'topicId', 'sourceId', 'title', 'body'])}
on conflict (id) do update set topic_id = excluded.topic_id, source_id = excluded.source_id, title = excluded.title, body = excluded.body;
`;

fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), sql);
console.log(`Wrote ${ideas.length} ideas from ${sources.length} sources to supabase/seed.sql`);
