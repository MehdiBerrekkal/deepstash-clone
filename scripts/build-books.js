// Turns the free-to-share EPUBs in books/ into full books on the Free classics shelf (see books/README.md).
// Each books/<id>.epub needs books/<id>.json with title, author, topicId, description, license and source.
// Output goes into src/data/classics/ next to the Gutenberg books: <id>.txt, an entry in index.json, and assets.ts.
// Usage: npm run books
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const root = path.join(__dirname, '..');
const booksDir = path.join(root, 'books');
const outDir = path.join(root, 'src', 'data', 'classics');
const indexFile = path.join(outDir, 'index.json');

const TOPICS = new Set([
  ...fs.readdirSync(path.join(root, 'src', 'data', 'library')).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')),
  'poetry',
]);
const REQUIRED = ['title', 'author', 'topicId', 'description', 'license', 'source'];

function fail(problems) {
  console.error(`\nNo books were changed. Fix these first:\n${problems.map((p) => `  - ${p}`).join('\n')}\n`);
  console.error('See books/README.md. Only public-domain or Creative Commons books may go in books/, because the repo is public.');
  process.exit(1);
}

function writeAssets(index) {
  const lines = index.map((b) => `  '${b.id}': require('./${b.id}.txt'),`).join('\n');
  fs.writeFileSync(
    path.join(outDir, 'assets.ts'),
    `// Generated by scripts/build-classics.js and scripts/build-books.js. Metro bundles each book as an asset that the reader loads on demand.\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const classicAssets: Record<string, number> = {\n${lines}\n};\n`,
  );
}

(async () => {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major < 22 || (major === 22 && minor < 18)) fail([`Node.js 22.18 or newer is needed (you have ${process.versions.node}).`]);

  const epubs = fs.existsSync(booksDir) ? fs.readdirSync(booksDir).filter((f) => f.toLowerCase().endsWith('.epub')) : [];
  const problems = [];
  const books = [];
  for (const file of epubs) {
    const id = file.replace(/\.epub$/i, '');
    const sidecar = path.join(booksDir, `${id}.json`);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) problems.push(`${file}: use a lowercase, hyphenated file name like "my-book.epub".`);
    if (!fs.existsSync(sidecar)) {
      problems.push(`${file}: missing books/${id}.json with the book's details and license.`);
      continue;
    }
    let meta;
    try {
      meta = JSON.parse(fs.readFileSync(sidecar, 'utf8'));
    } catch (e) {
      problems.push(`${id}.json: not valid JSON (${e.message}).`);
      continue;
    }
    for (const key of REQUIRED) if (!String(meta[key] ?? '').trim()) problems.push(`${id}.json: "${key}" is required.`);
    if (meta.license && !/^(public domain|cc0|cc[ -]by)/i.test(meta.license.trim())) {
      problems.push(`${id}.json: license must be "Public domain" or a Creative Commons license like "CC BY-SA 4.0" (got "${meta.license}").`);
    }
    if (meta.source && !/^https?:\/\//.test(meta.source)) problems.push(`${id}.json: "source" must be the web page you downloaded the book from.`);
    if (meta.topicId && !TOPICS.has(meta.topicId)) problems.push(`${id}.json: unknown topicId "${meta.topicId}". Use one of: ${[...TOPICS].join(', ')}.`);
    books.push({ id, file, meta });
  }

  const index = JSON.parse(fs.readFileSync(indexFile, 'utf8'));
  const taken = new Set(index.filter((b) => b.origin !== 'books').map((b) => b.id));
  for (const b of books) if (taken.has(b.id)) problems.push(`${b.file}: a bundled book already uses the id "${b.id}". Rename the file.`);
  if (problems.length) fail(problems);

  const { parseEpub } = await import(pathToFileURL(path.join(root, 'src', 'lib', 'epub.ts')).href);
  const added = [];
  for (const { id, file, meta } of books) {
    let parsed;
    try {
      parsed = await parseEpub(fs.readFileSync(path.join(booksDir, file)), file);
    } catch (e) {
      fail([`${file}: ${e.message}`]);
    }
    const chapters = parsed.chapters;
    const words = chapters.reduce((n, c) => n + c.paragraphs.join(' ').split(/\s+/).length, 0);
    fs.writeFileSync(path.join(outDir, `${id}.txt`), JSON.stringify({ chapters }));
    // Keep the first import date so "Recently added" and the NEW badge don't reset on every run.
    const previous = index.find((b) => b.id === id && b.origin === 'books');
    added.push({
      id,
      origin: 'books',
      addedAt: previous?.addedAt ?? new Date().toISOString(),
      title: meta.title,
      author: meta.author,
      ...(meta.translator ? { translator: meta.translator } : {}),
      year: Number(meta.year) || new Date().getFullYear(),
      topicId: meta.topicId,
      description: meta.description,
      license: meta.license,
      ...(meta.licenseUrl ? { licenseUrl: meta.licenseUrl } : {}),
      homepage: meta.source,
      chapters: chapters.length,
      words,
    });
    console.log(`ok  ${id}: ${chapters.length} chapters, ${words} words (${meta.license})`);
  }

  // Drop books that were removed from books/ and their text files.
  for (const old of index.filter((b) => b.origin === 'books' && !books.some((n) => n.id === b.id))) {
    fs.rmSync(path.join(outDir, `${old.id}.txt`), { force: true });
    console.log(`removed ${old.id}`);
  }
  added.sort((a, b) => b.addedAt.localeCompare(a.addedAt));
  const merged = [...index.filter((b) => b.origin !== 'books'), ...added];
  fs.writeFileSync(indexFile, JSON.stringify(merged, null, 2) + '\n');
  writeAssets(merged);
  console.log(`Free classics shelf now has ${merged.length} books (${added.length} from books/).`);
})();
